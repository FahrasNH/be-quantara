#!/usr/bin/env node
/**
 * shadow-weekly-report.js — Sprint 3 / MS-2
 *
 * Generates a weekly shadow-mode analysis report:
 *  1. Runs shadow analysis queries via ShadowCollectionService
 *  2. Formats a Markdown report
 *  3. Sends to Telegram via notifyInfo()
 *  4. Saves to data/shadow-reports/YYYY-WW.md
 *
 * Usage:
 *   node scripts/analytics/shadow-weekly-report.js
 *   node scripts/analytics/shadow-weekly-report.js --week 2026-W28
 */

"use strict";

require("dotenv").config();

const path = require("path");
const fs   = require("fs");

const ShadowCollectionService = require("../../src/server/services/ShadowCollectionService");
const { notifyInfo }          = require("../../src/infrastructure/notifications/TelegramNotifier");

// ── Parse CLI args ────────────────────────────────────────────────────────────

const args     = process.argv.slice(2);
const weekArg  = args.find(a => a.startsWith("--week="))?.split("=")[1];

// ── Week calculation ──────────────────────────────────────────────────────────

function getWeekBounds(weekStr) {
  if (weekStr) {
    // Parse "2026-W28" format
    const m = weekStr.match(/^(\d{4})-W(\d{2})$/);
    if (m) {
      const year = parseInt(m[1], 10);
      const week = parseInt(m[2], 10);
      const jan4 = new Date(Date.UTC(year, 0, 4));
      const startOfWeek1 = new Date(jan4);
      startOfWeek1.setUTCDate(jan4.getUTCDate() - ((jan4.getUTCDay() + 6) % 7));
      const start = new Date(startOfWeek1);
      start.setUTCDate(startOfWeek1.getUTCDate() + (week - 1) * 7);
      const end = new Date(start);
      end.setUTCDate(start.getUTCDate() + 6);
      end.setUTCHours(23, 59, 59, 999);
      return { start, end, label: weekStr };
    }
  }
  // Default: last completed week (Mon–Sun)
  const now   = new Date();
  const end   = new Date(now);
  end.setUTCDate(now.getUTCDate() - now.getUTCDay()); // last Sunday
  end.setUTCHours(23, 59, 59, 999);
  const start = new Date(end);
  start.setUTCDate(end.getUTCDate() - 6);
  start.setUTCHours(0, 0, 0, 0);

  // ISO week label
  const isoWeek = _isoWeek(start);
  return { start, end, label: `${start.getUTCFullYear()}-W${String(isoWeek).padStart(2, "0")}` };
}

function _isoWeek(date) {
  const d   = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const day = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - day);
  const yearStart = new Date(Date.UTC(d.getUTCFullYear(), 0, 1));
  return Math.ceil(((d - yearStart) / 86400000 + 1) / 7);
}

// ── Report formatter ──────────────────────────────────────────────────────────

function formatReport(weekLabel, report, promotionStatus) {
  const lines = [
    `# MetaSelector Shadow Report — ${weekLabel}`,
    ``,
    `**Period:** ${report.period}`,
    `**Mode:** Shadow (observation only)`,
    ``,
    `## Summary`,
    ``,
    `| Metric | Value |`,
    `|--------|-------|`,
    `| Total Signals | ${report.totalSignals} |`,
    `| Match Rate (bot = top rec) | ${report.matchRate}% |`,
    `| Win Rate Differential | ${report.winRateDiff > 0 ? "+" : ""}${report.winRateDiff}% |`,
    `| Hypothetical PnL | ${report.hypotheticalPnl} |`,
    `| Actual PnL | ${report.actualPnl} |`,
    ``,
    `## Regime Breakdown`,
    ``,
    `| Regime | Signals | Matches | Match Rate |`,
    `|--------|---------|---------|------------|`,
    ...(report.regimeBreakdown || []).map(r =>
      `| ${r.regime} | ${r.total} | ${r.matched} | ${r.matchRate}% |`
    ),
    ``,
    `## Promotion Readiness`,
    ``,
    `| Check | Value |`,
    `|-------|-------|`,
    `| Trade Count | ${promotionStatus.tradeCount} / 500 required |`,
    `| Confidence | ${promotionStatus.confidence || 0}% |`,
    `| Sharpe Diff | +${(promotionStatus.sharpeDiff || 0).toFixed(3)} |`,
    `| **Status** | **${promotionStatus.ready ? "✅ READY" : "⏳ NOT YET"}** |`,
    `| Reason | ${promotionStatus.reason} |`,
    ``,
    `---`,
    `*Generated by Quantara MetaSelector — ${new Date().toISOString()}*`,
  ];
  return lines.join("\n");
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  const { start, end, label } = getWeekBounds(weekArg);

  console.log(`[ShadowReport] Generating report for ${label} (${start.toISOString()} – ${end.toISOString()})`);

  const [report, promotionStatus] = await Promise.all([
    ShadowCollectionService.generateWeeklyReport(start, end),
    ShadowCollectionService.checkPromotionReadiness(),
  ]);

  const markdown = formatReport(label, report, promotionStatus);

  // Save to data/shadow-reports/YYYY-WW.md
  const reportsDir = path.join(__dirname, "../../data/shadow-reports");
  fs.mkdirSync(reportsDir, { recursive: true });
  const reportPath = path.join(reportsDir, `${label}.md`);
  fs.writeFileSync(reportPath, markdown, "utf8");
  console.log(`[ShadowReport] Saved to ${reportPath}`);

  // Send to Telegram
  const telegramSummary = [
    `📊 *MetaSelector Weekly Report — ${label}*`,
    ``,
    `• Signals: ${report.totalSignals}`,
    `• Match Rate: ${report.matchRate}%`,
    `• Win Rate Diff: ${report.winRateDiff > 0 ? "+" : ""}${report.winRateDiff}%`,
    `• Promotion: ${promotionStatus.ready ? "✅ Ready" : "⏳ " + promotionStatus.reason}`,
    ``,
    `Full report saved to \`data/shadow-reports/${label}.md\``,
  ].join("\n");

  await notifyInfo(telegramSummary);
  console.log(`[ShadowReport] Sent to Telegram`);

  console.log("\n" + markdown);
}

main().catch(err => {
  console.error("[ShadowReport] Error:", err);
  process.exit(1);
});
